#!/usr/bin/env python3
"""Rebuild apps.js from the SealSkin application catalog.

Reads apps.yml from linuxserver/sealskin-apps (a path or URL) and writes
the list the marquee shows: one entry per application, with the Webtop
desktop variants folded into one entry per distribution.

    python3 scripts/sync-apps.py                  # fetch the catalog from GitHub
    python3 scripts/sync-apps.py path/to/apps.yml # use a local copy
"""
import json
import re
import sys
import urllib.request

import yaml

CATALOG = "https://raw.githubusercontent.com/linuxserver/sealskin-apps/main/apps.yml"
DISTROS = {
    "alpine": "Alpine",
    "arch": "Arch",
    "debian": "Debian",
    "fedora": "Fedora",
    "ubuntu": "Ubuntu",
}
# Webtop variants no longer built; skipped if a stale catalog still lists them.
RETIRED = {"el"}
# Images that are a distribution's desktop of their own, shown beside the Webtop ones.
DESKTOP_IMAGES = {"kali-linux": "Kali Linux"}


def load(source):
    if re.match(r"^https?://", source):
        with urllib.request.urlopen(source, timeout=30) as response:
            return yaml.safe_load(response.read())
    with open(source, encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else CATALOG
    catalog = load(source)
    apps, desktops = [], {}
    for app in catalog["apps"]:
        app_id = app["id"]
        if app_id.startswith("webtop-"):
            parts = app_id[7:].split("-")
            distro = next((d for d in DISTROS if d in parts), None)
            if distro is None and RETIRED & set(parts):
                continue
            if distro:
                desktops.setdefault(distro, {"envs": [], "logo": app["logo"], "url": app["url"]})
                desktops[distro]["envs"].append(app["name"].split(" ")[0])
                continue
        if app_id in DESKTOP_IMAGES:
            apps.append({"name": f"{DESKTOP_IMAGES[app_id]} Desktop", "img": app["logo"], "url": app["url"]})
            continue
        apps.append({"name": app["name"], "img": app["logo"], "url": app["url"]})
    for distro, entry in desktops.items():
        apps.append({
            "name": f"{DISTROS[distro]} Desktop",
            "img": entry["logo"],
            "url": entry["url"],
            "note": ", ".join(dict.fromkeys(entry["envs"])),
        })
    apps.sort(key=lambda a: a["name"].lower())
    lines = ["// Generated by scripts/sync-apps.py from the SealSkin application catalog.",
             "// Do not edit by hand: run the script to refresh it.",
             "const apps = ["]
    for app in apps:
        lines.append("    " + json.dumps(app, ensure_ascii=False) + ",")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    with open("apps.js", "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{len(apps)} entries written to apps.js ({len(catalog['apps'])} catalog entries)")


if __name__ == "__main__":
    main()
